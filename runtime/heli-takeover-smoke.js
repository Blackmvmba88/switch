'use strict';
const assert=require('node:assert/strict');
const {HeliTakeover}=require('./heli-takeover');
const stamp=1000;
const state={timestampMs:stamp,pitchDeg:4,bankDeg:-5,pitchRateDegS:0,rollRateDegS:0,yawRateDegS:0,verticalSpeedFpm:-50,altitudeAglFt:150,headingDeg:270,airborne:true,onGround:false};
const s=new HeliTakeover();
assert.equal(s.tick(state).reason,'MANUAL');
assert.equal(s.toggle(state,stamp).reason,'ENGAGED');
const output=s.tick(state,{},stamp);
assert.equal(output.active,true);
assert.ok(Object.values(output.commands).every(x=>Math.abs(x)<=0.35));
assert.equal(s.tick(state,{axes:[0.5]},stamp).reason,'PILOT_OVERRIDE');
assert.equal(s.tick(state).active,false);
assert.equal(s.toggle({...state,timestampMs:100},stamp).reason,'TELEMETRY_UNAVAILABLE');
assert.equal(s.toggle(state,stamp).active,true);
assert.equal(s.tick(state,{},stamp+300).reason,'STALE_TELEMETRY');
assert.equal(s.toggle(state,stamp).active,true);
assert.equal(s.tick({...state,altitudeAglFt:3}, {},stamp).reason,'GROUND_OR_LOW_ALTITUDE');
console.log('OK heli takeover: manual, engage, bounds, override, stale telemetry, low altitude');
